import test from 'node:test';
import assert from 'node:assert/strict';
import { isBlockedIp } from '../src/ip.js';

const BLOCKED = ['127.0.0.1', '127.255.255.254', '10.0.0.1', '10.255.255.255', '172.16.0.1', '172.31.255.255', '192.168.0.1', '169.254.169.254', '169.254.170.2',
  '100.64.0.1', '100.127.255.255', '0.0.0.0', '0.1.2.3', '224.0.0.1', '239.255.255.255', '240.0.0.1', '255.255.255.255', '198.18.0.1', '198.19.255.255',
  '192.0.0.1', '192.0.2.1', '198.51.100.7', '203.0.113.9', '192.88.99.1',
  '::1', '::', 'fe80::1', 'fe80::abcd:1', 'fc00::1', 'fd12:3456:789a::1', 'ff02::1', 'fec0::1', '2001:db8::1', '2001::1', '2001:2::1', '3fff::1',
  '::ffff:127.0.0.1', '::ffff:7f00:1', '::ffff:10.0.0.1', '::ffff:169.254.169.254', '::127.0.0.1', '64:ff9b::7f00:1', '64:ff9b::808:808',
  '2002:7f00:0001::1', '2002:0a00:0001::', '2002:a9fe:a9fe::1',
  'garbage', '', '1.2.3', '256.1.1.1', '999.999.999.999', null, undefined, '[::1]', '0x7f.0.0.1', '2130706433'];
const ALLOWED = ['8.8.8.8', '1.1.1.1', '93.184.216.34', '172.15.255.255', '172.32.0.0', '100.63.255.255', '100.128.0.0', '192.0.1.1', '198.17.255.255', '198.20.0.0',
  '2606:4700:4700::1111', '2a00:1450:4007:80f::200e', '2001:4860:4860::8888', '::ffff:8.8.8.8', '2002:0808:0808::1', '[2606:4700:4700::1111]'];

test('every private, loopback, link-local, reserved and malformed address is blocked', () => {
  for (const ip of BLOCKED) assert.equal(isBlockedIp(ip), true, `should block ${ip}`);
});
test('public addresses are allowed (including neighbours of blocked ranges)', () => {
  for (const ip of ALLOWED) assert.equal(isBlockedIp(ip), false, `should allow ${ip}`);
});
